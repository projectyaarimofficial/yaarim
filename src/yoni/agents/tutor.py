"""סוכן ההוראה. שומר את היסטוריית השיחה ומסכם אותה בסיום."""

from typing import List, Optional, Tuple

from .base import StudentAgent

SYSTEM_PROMPT = """אתה יוני, מורה פרטי סבלני שמלמד תלמידים בעברית, בגילאי 10-16.

אתה מלמד את *כל* מקצועות בית הספר, ולא נושא אחד: מתמטיקה, לשון וכתיבה, אנגלית,
תנ"ך, היסטוריה, אזרחות, ספרות, גאוגרפיה, מדעים (פיזיקה, כימיה, ביולוגיה), מחשבים
ותכנות, אוריינות פיננסית, וכל מקצוע אחר שהתלמיד לומד. אם התלמיד שואל על נושא -
תלמד אותו, נקודה. אל תאמר "אני מלמד רק X" ואל תנתב אותו חזרה לנושא אחר.

יש לך גם מאגר תרגילים מובנה בחלק מהנושאים. זה יתרון שאתה מציע כשהוא רלוונטי -
לא גבול שמגדיר מה מותר ללמד.

אם אתה לא בטוח בעובדה (תאריך, נוסחה, ציטוט) - אמור שאתה לא בטוח במקום להמציא.
מורה שמודה שהוא לא זוכר מלמד את התלמיד דבר נכון; מורה שממציא מלמד אותו דבר שגוי.

הבחנה חשובה בין שני סוגי בקשות:

1. בקשת הסבר/הוראה (למשל: "תלמד אותי על X", "מה זה Y", "ספר לי על Z", "תסביר לי איך...") -
   הסבר ישירות ולעומק, בצורה ברורה ומדורגת. אל תשאל שאלה מנחה במקום להסביר.
   רק בסוף ההסבר, שאל שאלת הבנה אחת קצרה כדי לוודא שהתלמיד עקב אחרי ההסבר.

2. בקשת פתרון/תרגול (למשל: "תפתור את זה", "עזור לי עם התרגיל", "למה זה לא עובד", "יש לי שגיאה") -
   כאן כן להשתמש בשיטה סוקרטית: תן רמז ושאלה מנחה אחת שתעזור לתלמיד לחשוב בעצמו,
   לפני מתן התשובה המלאה. רק אם התלמיד מתקשה, טועה שוב, או מבקש מפורשות את הפתרון - תן תשובה ישירה.

התלמיד מחליט במה עוסקים. זה לא כלל נימוס - זה כלל עבודה:

- אל תפתח שיחה בהצעת נושא. שאל במה הוא רוצה לעסוק, וחכה לתשובה.
- אם קיבלת "רקע על התלמיד" עם נושא מוצע - זו *תשובה לשאלה שטרם נשאלה*.
  השתמש בו רק אם התלמיד ביקש הצעה, שאל "מה נלמד?", או אמר שאין לו העדפה.
- הצע נושא פעם אחת לכל היותר. אם התלמיד לא התלהב, שינה נושא, אמר "לא",
  "אחר כך", "משעמם" או פשוט שאל על משהו אחר - הנושא ירד מהשולחן. אל תחזור
  אליו, אל תשחיל אותו לדוגמאות, ואל תסיים כל תשובה ב"אז נחזור ל...".
- אם התלמיד שואל שאלה - ענה על *השאלה שלו*, לא על מה שתכננת ללמד.

אם התלמיד עונה "תתחיל", "כן", "קדימה", "בסדר", "לא יודע" וכדומה - זו הסכמה או המשך לשיחה
הקיימת, לא בקשה חדשה. המשך מהנקודה שבה עצרת (למשל תן את ההסבר או הרמז הבא), אל תגיד "אני לא מבין".

אם שאלת שאלת הבהרה (למשל "האם אתה מתכוון ל-א' או ל-ב'") והתלמיד חוזר על אחת האפשרויות
או עונה בקצרה - קבל את זה כבחירה ברורה וקדם את השיחה בהתאם. לעולם אל תחזור מילה במילה
על הודעה שכבר שלחת - אם אתה לא בטוח מה מבקשים ממך, נסח שאלת הבהרה חדשה ושונה.

ענה תמיד בעברית, בקצרה ובאדיבות."""

#: נוסף לפרומפט כשהתלמיד *שומע* את התשובה במקום לקרוא אותה. טקסט מדובר
#: נצרך לאט הרבה יותר מטקסט כתוב: פסקה שנקראת בחמש שניות נשמעת חצי דקה.
#: זה גם מה שמקצר את ההמתנה - רוב הזמן הולך על יצירת הטקסט.
SPOKEN_STYLE = """
התלמיד *שומע* אותך, לא קורא. לכן:
- ענה ב-2 עד 4 משפטים. זו שיחה, לא הרצאה.
- בלי רשימות, בלי כותרות, בלי סימני עיצוב - הם נשמעים רע כשמקריאים אותם.
- מספרים ונוסחאות - במילים ("שני שליש", לא "2/3").
- אם הנושא גדול, תן חתיכה אחת ושאל אם להמשיך. אל תשפוך הכל בבת אחת."""

SUMMARY_PROMPT = """סכם בקצרה ובעברית (2-3 משפטים) את השיחה הלימודית הבאה בין יוני (מורה) לתלמיד:

{transcript}
"""


class Tutor(StudentAgent):
    """שיחה לימודית בעברית. ההיסטוריה היא מצב של הסוכן, לא של הממשק."""

    #: כמה תורות משיחות קודמות נכנסים לפרומפט. כל תור כאן נשלח מחדש בכל
    #: הודעה, ולכן המספר הזה הוא ישירות זמן ההמתנה של התלמיד. 12 מספיק כדי
    #: שיוני יזכור על מה דיברתם; 30 רק האט את התשובה.
    MEMORY_TURNS = 12

    def __init__(self, language_model, model_name: str,
                 context: Optional[str] = None, spoken: bool = False) -> None:
        super().__init__(language_model, model_name)
        self._history: List[Tuple[str, str]] = []
        self._memory: List[Tuple[str, str]] = []
        self._context = context or ""
        self._spoken = spoken

    def set_spoken(self, spoken: bool) -> None:
        """המתג בין דיבור לכתב משנה *איך* יוני עונה, לא רק אם מקריאים."""
        self._spoken = bool(spoken)

    @property
    def history(self) -> Tuple[Tuple[str, str], ...]:
        return tuple(self._history)

    @property
    def message_count(self) -> int:
        return len(self._history)

    def remember(self, turns) -> None:
        """טוען תורות משיחות *קודמות*. אינם חלק מהשיחה הנוכחית ולא ייספרו בה."""
        self._memory = [(self._speaker(s), t) for s, t in turns][-self.MEMORY_TURNS:]

    def load_history(self, turns) -> None:
        """משחזר שיחה שנקטעה - אלה כן התורות של השיחה הנוכחית."""
        self._history = [(self._speaker(s), t) for s, t in turns]

    @staticmethod
    def _speaker(speaker: str) -> str:
        """התמליל שומר student/yoni; הפרומפט מדבר עברית."""
        return {"student": "תלמיד", "yoni": "יוני"}.get(speaker, speaker)

    def _transcript(self):
        return "\n".join(f"{speaker}: {text}" for speaker, text in self._history)

    def build_prompt(self, student_message: Optional[str] = None) -> str:
        head = SYSTEM_PROMPT + (SPOKEN_STYLE if self._spoken else "")
        if self._memory:
            past = "\n".join(f"{s}: {t}" for s, t in self._memory)
            head = (
                f"{head}\n\nמה שכבר דיברתם עליו בפגישות קודמות (לידיעתך בלבד - "
                f"אל תפתח בזה ואל תצטט את זה, פשוט אל תשאל שוב מה שכבר ידוע לך):"
                f"\n{past}"
            )
        if self._context:
            head = f"{head}\n\nרקע על התלמיד: {self._context}"
        return f"{head}\n\nהיסטוריית השיחה:\n{self._transcript()}\nיוני:"

    def ask(self, student_message: str) -> str:
        self._history.append(("תלמיד", student_message))
        reply = self._ask(self.build_prompt())
        self._history.append(("יוני", reply))
        return reply

    def summarize(self) -> str:
        if not self._history:
            return "(שיחה ריקה - אין מה לסכם)"
        return self._ask(SUMMARY_PROMPT.format(transcript=self._transcript()))

    def reset(self) -> None:
        self._history = []
